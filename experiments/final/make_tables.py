def table_benchmark(manifest: dict) -> str:
    lines = [BANNER, "", "### Benchmark accounting", "",
             "Generated from `benchmark/benchmark_manifest.json`.", ""]
    corpus = manifest["corpus"]
    lines += [
        f"Corpus: **{corpus['n_files_on_disk']}** program files on disk, "
        f"**{corpus['n_assigned_to_splits']}** assigned to splits, "
        f"**{corpus['n_unassigned']}** unassigned "
        f"({', '.join('`' + p + '`' for p in corpus['unassigned_programs'])}). "
        "Unassigned programs take part in no experiment.", "",
    ]
    for name, block in manifest["datasets"].items():
        lines += [f"**{name}** (`{block['dataset_dir']}`)", "",
                  "| Split | Programs | Nominal pairs | Uncompilable | No entry fn | "
                  "CHANGED unobservable | Statically valid |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for split, s in block["splits"].items():
            lines.append(
                f"| {split} | {s['n_programs']} | {s['nominal_pairs']} | "
                f"{s['excluded_uncompilable']} | {s['excluded_no_entry_function']} | "
                f"{s['excluded_changed_unobservable']} | {s['statically_valid_pairs']} |")
        t = block["totals"]
        lines.append(
            f"| **total** | **{t['n_programs']}** | **{t['nominal_pairs']}** | "
            f"**{t['excluded_uncompilable']}** | **{t['excluded_no_entry_function']}** | "
            f"**{t['excluded_changed_unobservable']}** | "
            f"**{t['statically_valid_pairs']}** |")
        lines += ["", f"Split program intersections all empty: "
                      f"**{block['all_intersections_empty']}**", ""]
    return "\n".join(lines) + "\n"


