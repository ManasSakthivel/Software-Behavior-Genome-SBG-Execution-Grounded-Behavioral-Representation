def table_main(evaluations: Dict[str, dict]) -> str:
    lines = [BANNER, "", "### Main benchmark — AUROC by predictor", "",
             "Every predictor is computed from the *same* execution traces, so the "
             "comparison differs only in the feature used. AUROC is tie-aware "
             "Wilcoxon–Mann–Whitney; the interval is a cluster bootstrap resampling "
             "base programs; the p-value permutes labels within clusters.", ""]

    for label, payload in evaluations.items():
        if payload is None:
            continue
        lines += [f"**{label}** — split `{payload['split']}`, "
                  f"protocol `{payload['protocol']}`", ""]
        sizes = payload["set_sizes"]
        lines += [f"Set sizes: ALL={sizes['ALL']}, EVALUABLE={sizes['EVALUABLE']}, "
                  f"VALID={sizes['VALID']}.", ""]
        for set_name in ("ALL", "EVALUABLE", "VALID"):
            block = payload["results"][set_name]["predictors"]
            scored = [(k, v) for k, v in block.items() if v.get("auroc") is not None]
            if not scored:
                continue
            lines += [f"*{set_name}*", "",
                      "| Predictor | AUROC | 95% CI (cluster bootstrap) | p (within-cluster perm.) | n |",
                      "|---|---:|---|---:|---:|"]
            for name, stats in sorted(scored, key=lambda kv: -kv[1]["auroc"]):
                lines.append(
                    f"| `{name}` | {stats['auroc']:.4f} | "
                    f"{fmt_ci(stats['ci95_cluster_bootstrap'])} | "
                    f"{fmt_p(stats['permutation_p'])} | {stats['n']} |")
            lines.append("")

        comparisons = payload["results"]["VALID"]["paired_comparisons"]
        pairs = {k: v for k, v in comparisons.items() if k != "holm_bonferroni"}
        if pairs:
            holm = comparisons.get("holm_bonferroni", {})
            lines += ["*Paired comparisons on VALID* — ΔAUROC with a paired cluster "
                      "bootstrap. Overlapping marginal intervals are not a test of a "
                      "difference; this is.", "",
                      "| Comparison | ΔAUROC | 95% CI | p (two-sided) | p (Holm) | Reject H₀ |",
                      "|---|---:|---|---:|---:|---|"]
            for name, block in pairs.items():
                adj = holm.get(name, {})
                lines.append(
                    f"| `{name}` | {block['delta']:+.4f} | "
                    f"{fmt_ci([block['ci_lower'], block['ci_upper']])} | "
                    f"{fmt_p(block['p_two_sided'])} | "
                    f"{fmt_p(adj.get('p_adjusted'))} | "
                    f"{'yes' if adj.get('reject_at_alpha') else 'no'} |")
            lines.append("")

        noise = payload["results"]["VALID"].get("label_shuffle_noise_floor_primary")
        if noise:
            lines += [f"Label-shuffle noise floor for `{payload['primary_predictor']}` "
                      f"on VALID: mean {noise['mean']:.4f}, 95th percentile "
                      f"**{noise['p95']:.4f}** over {noise['n_shuffles']} shuffles. "
                      "An AUROC below that percentile is not evidence of signal.", ""]

        lines += ["*Unevaluable pairs, by cause* — none are discarded; on `ALL` they "
                  "are scored at distance 0, which charges the failure to the method.",
                  "", "| Cause | Pairs |", "|---|---:|"]
        for cause, count in payload["failure_ledger"].items():
            lines.append(f"| `{cause}` | {count} |")
        lines.append("")
    return "\n".join(lines) + "\n"


