def headline_numbers(manifest: dict, evaluations: Dict[str, Optional[dict]],
                     hard: dict, regression: dict, leak: dict) -> dict:
    out: Dict[str, Any] = {
        "_note": ("Every number quoted in the README, the manuscript or a figure "
                  "must appear here and must be produced by make_tables.py from an "
                  "artifact. consistency_check.py enforces it."),
        "corpus_files_on_disk": manifest["corpus"]["n_files_on_disk"],
        "corpus_programs_assigned": manifest["corpus"]["n_assigned_to_splits"],
        "corpus_programs_unassigned": manifest["corpus"]["n_unassigned"],
    }
    for name, block in manifest["datasets"].items():
        out[f"{name}_total_pairs"] = block["totals"]["nominal_pairs"]
        out[f"{name}_total_valid_pairs"] = block["totals"]["statically_valid_pairs"]
        out[f"{name}_test_pairs"] = block["splits"]["test"]["nominal_pairs"]
        out[f"{name}_test_valid_pairs"] = block["splits"]["test"]["statically_valid_pairs"]
        out[f"{name}_test_programs"] = block["splits"]["test"]["n_programs"]

    for label, payload in evaluations.items():
        if payload is None:
            continue
        key = label.lower().replace(" ", "_").replace("—", "").replace("--", "_")
        for set_name in ("ALL", "EVALUABLE", "VALID"):
            block = payload["results"][set_name]["predictors"]
            for predictor, stats in block.items():
                if stats.get("auroc") is None:
                    continue
                out[f"{key}.{set_name}.{predictor}.auroc"] = stats["auroc"]
                out[f"{key}.{set_name}.{predictor}.ci"] = stats["ci95_cluster_bootstrap"]
                out[f"{key}.{set_name}.{predictor}.n"] = stats["n"]
        out[f"{key}.set_sizes"] = payload["set_sizes"]
        out[f"{key}.failure_ledger"] = payload["failure_ledger"]

    for regime, block in hard["regimes"].items():
        for name, m in block["metrics"].items():
            out[f"hard_negatives.{regime}.{name}.correct"] = m["tp"] + m["tn"]
            out[f"hard_negatives.{regime}.{name}.n"] = m["n_scored"]
    for name, block in regression["all_pairs"].items():
        out[f"regression.{name}.detected"] = block["n_detected"]
        out[f"regression.{name}.n"] = block.get("n_scored", block.get("n_total"))
    sb = regression["silent_bugs_only"]
    out["regression.silent_bugs.sbg_v5.detected"] = sb["sbg_v5_output_free"]["n_detected"]
    out["regression.silent_bugs.sbg_v5.n"] = sb["sbg_v5_output_free"]["n_scored"]
    out["regression.silent_bugs.output_reference.detected"] = \
        sb["output_reading_reference"]["n_detected"]

    s = leak["corpus_summary"]
    out["leak.programs"] = s["n_programs"]
    out["leak.entry_is_self_test_driver"] = s["n_entry_is_self_test_driver"]
    out["leak.entry_traces_assertions"] = s["n_entry_traces_assertions"]
    out["leak.assert_statements_traced"] = s["total_assert_statements_traced"]
    out["leak.canonical_inputs_unused"] = s["n_canonical_inputs_unused"]
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", default=str(REPO_ROOT / "docs" / "generated"))
    parser.add_argument("--allow-missing", action="store_true",
                        help="skip tables whose artifact is absent (development only)")
    args = parser.parse_args()
    out_dir = pathlib.Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    manifest = load(REPO_ROOT / "benchmark" / "benchmark_manifest.json")
    evaluations = {
        "Published protocol": load(ARTIFACTS / "MAIN_EVALUATION_test_published.json"),
        "Output-free protocol v6": load(
            ARTIFACTS / "MAIN_EVALUATION_test_output_free_v6.json"),
        "Output-free protocol v6, corrected benchmark": load(
            ARTIFACTS / "MAIN_EVALUATION_v6test_output_free_v6.json"),
    }
    hard = load(ARTIFACTS / "HARD_NEGATIVE_V5_RESULTS.json")
    regression = load(ARTIFACTS / "REGRESSION_V5_RESULTS.json")
    leak = load(ARTIFACTS / "OUTPUT_ORACLE_LEAK_AUDIT.json")

    missing = [name for name, value in
               (("benchmark_manifest.json", manifest),
                ("HARD_NEGATIVE_V5_RESULTS.json", hard),
                ("REGRESSION_V5_RESULTS.json", regression),
                ("OUTPUT_ORACLE_LEAK_AUDIT.json", leak))
               if value is None]
    if not any(evaluations.values()):
        missing.append("MAIN_EVALUATION_*.json")
    if missing and not args.allow_missing:
        print("missing authoritative artifacts: " + ", ".join(missing), file=sys.stderr)
        return 1

    written = []
    if manifest:
        (out_dir / "table_benchmark.md").write_text(table_benchmark(manifest))
        written.append("table_benchmark.md")
    if any(evaluations.values()):
        (out_dir / "table_main_evaluation.md").write_text(table_main(evaluations))
        written.append("table_main_evaluation.md")
    if hard:
        (out_dir / "table_hard_negatives.md").write_text(table_hard_negatives(hard))
        written.append("table_hard_negatives.md")
    if regression:
        (out_dir / "table_regression.md").write_text(table_regression(regression))
        written.append("table_regression.md")
    if leak:
        (out_dir / "table_output_free_audit.md").write_text(table_leak(leak))
        written.append("table_output_free_audit.md")

    if manifest and hard and regression and leak:
        (out_dir / "readme_results.md").write_text(
            readme_results(manifest, evaluations, hard, regression, leak))
        written.append("readme_results.md")
        numbers = headline_numbers(manifest, evaluations, hard, regression, leak)
        (out_dir / "headline_numbers.json").write_text(
            json.dumps(numbers, indent=2, sort_keys=True) + "\n")
        written.append("headline_numbers.json")

    for name in written:
        path = out_dir / name
        try:
            print(f"wrote {path.relative_to(REPO_ROOT)}")
        except ValueError:
            print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
