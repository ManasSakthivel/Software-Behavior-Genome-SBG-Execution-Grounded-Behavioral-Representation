def table_regression(payload: dict) -> str:
    lines = [BANNER, "", "### Regression corpus (15 buggy/fixed pairs)", "",
             f"Detection at \u03c4* = {payload['threshold_tau_star']}. Every pair is a "
             "genuine bug, so only recall is defined.", "",
             "| Method | Reads output | Detected | Rate | 95% CI (Wilson) |",
             "|---|---|---:|---:|---|"]
    for name, block in payload["all_pairs"].items():
        reads = "yes" if name.startswith("output_reading") else "no"
        total = block.get("n_scored", block.get("n_total"))
        rate = block.get("detection_rate")
        lines.append(
            f"| `{name}` | {reads} | {block['n_detected']}/{total} | "
            f"{rate:.3f} | {fmt_ci(block.get('detection_rate_95ci_wilson'))} |")
    silent = payload["silent_bugs_only"]
    sbg = silent["sbg_v5_output_free"]
    ref = silent["output_reading_reference"]
    lines += ["", f"Silent bugs ({silent['definition']}): SBG V5 detects "
                  f"**{sbg['n_detected']}/{sbg['n_scored']}**; the output-reading "
                  f"reference detects {ref['n_detected']}/{ref['n_total']}.", ""]
    return "\n".join(lines) + "\n"


