#!/usr/bin/env python3
"""
experiments/final/make_tables.py
================================
Generates every quantitative table and the headline-number index from the
authoritative artifacts. Nothing downstream types a number by hand.

Chain enforced here:

    source code -> experiment -> raw per-pair record -> authoritative artifact
                -> docs/generated/*.md  ->  README / manuscript
                -> docs/generated/headline_numbers.json -> consistency_check.py

``experiments/final/consistency_check.py`` re-runs this script into a temporary
directory and fails if the committed output differs, so a table can never drift
from the artifact it came from.

Usage:
    python3 experiments/final/make_tables.py [--out-dir docs/generated]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any, Dict, Optional

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
ARTIFACTS = REPO_ROOT / "artifacts" / "final"

BANNER = ("<!-- GENERATED BY experiments/final/make_tables.py -- DO NOT EDIT BY HAND. "
          "Run `make tables` after changing an artifact. -->")


def load(path: pathlib.Path) -> Optional[dict]:
    if not path.exists():
        return None
    return json.loads(path.read_text())


def fmt_ci(ci) -> str:
    if not ci or ci[0] is None:
        return "—"
    return f"[{ci[0]:.3f}, {ci[1]:.3f}]"


def fmt_p(p) -> str:
    if p is None:
        return "—"
    return f"{p:.4f}" if p >= 0.0005 else f"<{0.0005:.4f}"


