def table_leak(payload: dict) -> str:
    s = payload["corpus_summary"]
    lines = [BANNER, "", "### Output-free constraint — protocol audit", "",
             "Static analysis; no program is executed.", "",
             "| Quantity | Value |", "|---|---:|",
             f"| Corpus programs | {s['n_programs']} |",
             f"| Entry function is a self-test driver | {s['n_entry_is_self_test_driver']} |",
             f"| Entry function traces `assert` statements | {s['n_entry_traces_assertions']} "
             f"({s['fraction_leaking']:.1%}) |",
             f"| `assert` statements inside traced regions | {s['total_assert_statements_traced']} |",
             f"| Programs where the canonical inputs are never used | "
             f"{s['n_canonical_inputs_unused']} |", "",
             "| Split | Programs | Leaking |", "|---|---:|---:|"]
    for split, block in payload["by_split"].items():
        lines.append(f"| {split} | {block['n_programs']} | "
                     f"{block['n_entry_traces_assertions']} |")
    lines += ["", payload["finding"], "", payload["consequence_for_published_claims"], ""]
    return "\n".join(lines) + "\n"



