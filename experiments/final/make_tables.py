README_BEGIN = "<!-- BEGIN GENERATED RESULTS -->"
README_END = "<!-- END GENERATED RESULTS -->"


def _predictor_rows(payload: dict, set_name: str, names) -> list:
    block = payload["results"][set_name]["predictors"]
    rows = []
    for name in names:
        stats = block.get(name, {})
        if stats.get("auroc") is None:
            continue
        rows.append((name, stats["auroc"], stats["ci95_cluster_bootstrap"], stats["n"]))
    return rows


